// Desarrollar un programa que calcule la factorial de un número en forma recursiva.

#include <stdio.h>

int factorial(int n) {}

int main()
{
    int n;
    printf("Ingrese un numero entero positivo: ");
    scanf("%d", &n);
    
    printf("El factorial de %d es %d\n", n, factorial(n));
    
    return 0;
}